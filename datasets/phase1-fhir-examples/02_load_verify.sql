-- Run AFTER uploading all 11 files in s3_upload/ to the specified S3 folder.
-- Stop on an error. Execute this file in one worksheet session.
USE WAREHOUSE FIRELY_DEMO_WH;
USE DATABASE CHATGPT_LAB;
USE SCHEMA FHIR_HL7_EXAMPLES;
CREATE OR REPLACE TEMP TABLE LOAD_WORK LIKE RESOURCE_RAW;
COPY INTO LOAD_WORK
 (SOURCE_DATASET,BATCH_ID,RESOURCE_TYPE,RESOURCE_ID,PAYLOAD,
 SOURCE_FILENAME,FILE_ROW_NUMBER,LOADED_AT)
FROM (SELECT 'hl7_r4_official_examples','hl7-r4-examples-20261008-v1',
 t.$1:resourceType::VARCHAR,t.$1:id::VARCHAR,t.$1,
 METADATA$FILENAME,METADATA$FILE_ROW_NUMBER,METADATA$START_SCAN_TIME
 FROM @HL7_EXAMPLES_S3 t)
FILES=('Patient.ndjson','Appointment.ndjson','Observation.ndjson',
 'Condition.ndjson','Medication.ndjson','MedicationRequest.ndjson',
 'MedicationStatement.ndjson','AllergyIntolerance.ndjson','Encounter.ndjson',
 'DiagnosticReport.ndjson','DocumentReference.ndjson')
FILE_FORMAT=(FORMAT_NAME='HL7_JSON') ON_ERROR=ABORT_STATEMENT FORCE=FALSE;
-- Expected: 933; check COPY result for every file as well.
SELECT COUNT(*) AS LANDING_ROWS FROM LOAD_WORK;
-- All following checks must be zero; inspect before running MERGE.
SELECT RESOURCE_TYPE,RESOURCE_ID,COUNT(*) AS COPIES FROM LOAD_WORK
GROUP BY 1,2 HAVING COUNT(*)>1;
SELECT * FROM LOAD_WORK WHERE RESOURCE_TYPE IS NULL OR RESOURCE_ID IS NULL;
SELECT s.RESOURCE_TYPE,s.RESOURCE_ID FROM LOAD_WORK s JOIN RESOURCE_RAW t
 ON t.SOURCE_DATASET=s.SOURCE_DATASET AND t.BATCH_ID=s.BATCH_ID
 AND t.RESOURCE_TYPE=s.RESOURCE_TYPE AND t.RESOURCE_ID=s.RESOURCE_ID
WHERE t.PAYLOAD IS DISTINCT FROM s.PAYLOAD;
-- Immutable batch: fail closed if count, IDs, duplicates, or conflicts differ.
EXECUTE IMMEDIATE $$
DECLARE
 invalid_load EXCEPTION (-20001, 'Load validation failed: check landing count, IDs, duplicates and payload conflicts.');
 n NUMBER;
 bad NUMBER;
BEGIN
 SELECT COUNT(*) INTO :n FROM LOAD_WORK;
 SELECT COUNT(*) INTO :bad FROM (
   SELECT RESOURCE_TYPE,RESOURCE_ID FROM LOAD_WORK
   GROUP BY 1,2 HAVING COUNT(*)>1 OR RESOURCE_TYPE IS NULL OR RESOURCE_ID IS NULL
 );
 IF (n <> 933 OR bad <> 0) THEN RAISE invalid_load; END IF;
 SELECT COUNT(*) INTO :bad FROM LOAD_WORK s JOIN RESOURCE_RAW t
 ON t.SOURCE_DATASET=s.SOURCE_DATASET AND t.BATCH_ID=s.BATCH_ID
 AND t.RESOURCE_TYPE=s.RESOURCE_TYPE AND t.RESOURCE_ID=s.RESOURCE_ID
 WHERE t.PAYLOAD IS DISTINCT FROM s.PAYLOAD;
 IF (bad <> 0) THEN RAISE invalid_load; END IF;
 MERGE INTO RESOURCE_RAW t USING LOAD_WORK s
 ON t.SOURCE_DATASET=s.SOURCE_DATASET AND t.BATCH_ID=s.BATCH_ID
 AND t.RESOURCE_TYPE=s.RESOURCE_TYPE AND t.RESOURCE_ID=s.RESOURCE_ID
 WHEN NOT MATCHED THEN INSERT
 (SOURCE_DATASET,BATCH_ID,RESOURCE_TYPE,RESOURCE_ID,PAYLOAD,SOURCE_FILENAME,FILE_ROW_NUMBER,LOADED_AT)
 VALUES(s.SOURCE_DATASET,s.BATCH_ID,s.RESOURCE_TYPE,s.RESOURCE_ID,s.PAYLOAD,s.SOURCE_FILENAME,s.FILE_ROW_NUMBER,s.LOADED_AT);
 RETURN 'Validated landing data and merged immutable batch.';
END;
$$;
SELECT RESOURCE_TYPE,COUNT(*) AS RECORDS FROM RESOURCE_RAW
WHERE SOURCE_DATASET='hl7_r4_official_examples' AND BATCH_ID='hl7-r4-examples-20261008-v1'
GROUP BY 1 ORDER BY 1;
-- Expected target rows: 933. Same batch rerun inserts zero.
SELECT COUNT(*) AS TARGET_ROWS FROM RESOURCE_RAW
WHERE SOURCE_DATASET='hl7_r4_official_examples' AND BATCH_ID='hl7-r4-examples-20261008-v1';
